"""Build data/analysis/comparison.md from data/analysis/findings/*.json.

One table per question (collected, used for, shared with, kept, controls, plus the
AI / sensitive-data / opt-out angle). One row per platform; each cell lists that platform's
findings for the question as: claim, exact quote, file:line. Topics a policy does not
address are shown as "not stated".
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FINDINGS = os.path.join(ROOT, "data/analysis/findings")
# eBay: the notice in force on the retrieval date is ranked; the upcoming one is reported as changes.
EXCLUDE = {"ebay", "ebay_changes"}

SECTIONS = [
    ("What they collect", ["collect_provided", "collect_automatic", "collect_inferred", "collect_third_party"]),
    ("What they use it for", ["use_ads", "use_personalization", "use_research", "use_ai_training"]),
    ("Who they share it with, and what \"selling\" means", ["share_third_parties", "sell_share_definition"]),
    ("How long they keep it", ["retention"]),
    ("What users can control", ["user_controls", "optout_ads", "optout_ai", "optout_steps"]),
    ("Sensitive data", ["sensitive_location", "sensitive_biometric", "sensitive_health", "sensitive_children"]),
]
LABELS = {
    "collect_provided": "you give", "collect_automatic": "automatic", "collect_inferred": "inferred",
    "collect_third_party": "from others", "use_ads": "ads", "use_personalization": "personalization",
    "use_research": "research", "use_ai_training": "AI training", "share_third_parties": "shares with",
    "sell_share_definition": "sell/share", "retention": "retention", "user_controls": "controls",
    "optout_ads": "ad opt-out", "optout_ai": "AI opt-out", "optout_steps": "opt-out steps",
    "sensitive_location": "location", "sensitive_biometric": "biometric", "sensitive_health": "health",
    "sensitive_children": "children",
}


def load():
    out = []
    for p in sorted(glob.glob(os.path.join(FINDINGS, "*.json"))):
        key = os.path.splitext(os.path.basename(p))[0]
        if key in EXCLUDE:
            continue
        with open(p, encoding="utf-8") as f:
            out.append(json.load(f))
    return sorted(out, key=lambda d: d["platform"].lower())


def cell(d, topics):
    parts = []
    for t in topics:
        fs = [f for f in d["findings"] if f["topic"] == t]
        if not fs and any(n["topic"] == t for n in d.get("not_stated", [])):
            parts.append(f"**{LABELS[t]}:** *not stated*")
        for f in fs:
            q = f["quote"].replace("|", "\\|")
            parts.append(f"**{LABELS[t]}:** {f['claim']} — “{q}” (`{d['file']}:{f['line']}`)")
    return "<br><br>".join(parts) if parts else "*not stated*"


def main():
    docs = load()
    lines = ["# Privacy policy comparison", "",
             f"Generated by `data/analysis/build_comparison.py` from `data/analysis/findings/`. "
             f"{len(docs)} platforms. Each entry: plain-language claim — exact quote (file:line). "
             "Quotes are checked by `data/analysis/check_quotes.py`.", ""]
    for title, topics in SECTIONS:
        lines += [f"## {title}", "", "| Platform | Findings |", "|---|---|"]
        for d in docs:
            lines.append(f"| {d['platform']} | {cell(d, topics)} |")
        lines.append("")
    out = os.path.join(ROOT, "data/analysis/comparison.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(out, ROOT)}: {len(docs)} platforms, "
          f"{sum(len(d['findings']) for d in docs)} findings")


if __name__ == "__main__":
    main()
